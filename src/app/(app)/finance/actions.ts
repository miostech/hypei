"use server";

import { randomUUID } from "node:crypto";
import { revalidatePath } from "next/cache";
import { z } from "zod";
import { ForbiddenError } from "@/lib/errors";
import { getAppDictionary } from "@/lib/i18n/app";
import { appLocale } from "@/lib/i18n/app/server";
import { fill, plural } from "@/lib/i18n/locale";
import { assertSupportedCurrency, parseDecimalToMinorUnits } from "@/lib/money";
import { formatAmount } from "@/lib/ui/format";
import { requirePermission } from "@/modules/organizations/current-organization";
import { getServices } from "@/server/container";
import { runAction, type ActionState } from "@/server/actions/action-state";

const payoutSchema = z.object({
  amount: z.string().trim().regex(/^\d{1,9}([.,]\d{1,2})?$/, "Valor inválido"),
  /** A moeda do saldo que está na tela: cada moeda é um saldo, e o saque sai de um deles. */
  currency: z.string(),
  /** Generated by the client per dialog session so retries never duplicate a payout. */
  requestId: z.string().uuid().optional(),
});

export async function requestPayout(_prev: ActionState, formData: FormData): Promise<ActionState> {
  return runAction(async () => {
    const { organization, userId } = await requirePermission("payouts:request");
    const input = payoutSchema.parse({
      amount: formData.get("amount"),
      currency: formData.get("currency"),
      requestId: formData.get("requestId") ?? undefined,
    });
    const currency = assertSupportedCurrency(input.currency);

    await getServices().payouts.request({
      organizationId: organization.id,
      amount: parseDecimalToMinorUnits(input.amount, currency),
      currency,
      idempotencyKey: `payout:${organization.id}:${input.requestId ?? randomUUID()}`,
      userId,
    });

    revalidatePath("/finance");
    return { status: "success", message: (await getAppDictionary(await appLocale())).toasts.payoutRequested };
  });
}

/**
 * Pedido de recebimento de cartão em 2 dias.
 *
 * A resposta vem na hora e é sempre a mesma pergunta: quanto esta conta já vendeu. Negado não
 * é erro de quem pediu — é a condição ainda não valer —, por isso a mensagem explica o que
 * falta em vez de só dizer que não deu.
 */
export async function requestFastSettlement(): Promise<ActionState> {
  return runAction(async () => {
    const { organization, userId } = await requirePermission("payouts:request");
    const currency = assertSupportedCurrency(organization.defaultCurrency);
    const decision = await getServices().settlements.requestFastCardSettlement({
      organizationId: organization.id,
      currency,
      userId,
    });
    const dict = await getAppDictionary(await appLocale());
    const t = dict.finance.terms;
    if (!decision.granted) {
      return { status: "error", message: fill(t.fastDenied, { amount: formatAmount(decision.minimumRevenue, currency) }) };
    }
    revalidatePath("/finance");
    return { status: "success", message: t.fastGranted };
  });
}

/**
 * Development helper that runs the settlement routine as if the window had elapsed,
 * so PENDING → AVAILABLE can be exercised without waiting D+N. Never enabled in production.
 */
export async function simulateSettlement(): Promise<ActionState> {
  return runAction(async () => {
    if (process.env.APP_ENV === "production") throw new ForbiddenError("Indisponível em produção");
    const { organization } = await requirePermission("finance:read");
    const future = new Date(Date.now() + 365 * 86_400_000);
    const services = getServices();
    const result = await services.settlements.releaseDue({ now: future, organizationId: organization.id });
    // A reserva vence depois da venda liberar, então ela vem junto no mesmo pulo no tempo.
    await services.reserves.releaseDue({ now: future, organizationId: organization.id });
    revalidatePath("/finance");
    revalidatePath("/dashboard");
    const dict = await getAppDictionary(await appLocale());
    return {
      status: "success",
      message:
        result.processed === 0
          ? dict.finance.noSettlement
          : plural(dict.locale, result.processed, dict.finance.settlementDone),
    };
  });
}
